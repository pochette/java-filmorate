CREATE TABLE IF NOT EXISTS users (
                                     user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     name VARCHAR(255),
                                     email VARCHAR(255) NOT NULL UNIQUE,
                                     login VARCHAR(255) NOT NULL UNIQUE,
                                     birthday DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS genre_type (
                                          genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS mpa_type (
                                        mpa_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        mpa_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS films (
                                     film_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     name VARCHAR(255) NOT NULL,
                                     description VARCHAR(1000) NOT NULL,
                                     release_date DATE NOT NULL,
                                     duration INTEGER NOT NULL CHECK (duration > 0),
                                     mpa_id INTEGER NOT NULL REFERENCES mpa_type(mpa_id)
);

CREATE TABLE IF NOT EXISTS film_genres (
                                           film_id INTEGER NOT NULL REFERENCES films(film_id) ON DELETE CASCADE,
                                           genre_id INTEGER NOT NULL REFERENCES genre_type(genre_id) ON DELETE CASCADE,
                                           PRIMARY KEY (film_id, genre_id)
);

CREATE TABLE IF NOT EXISTS friends (
                                       user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                       friend_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                       confirmed BOOLEAN NOT NULL DEFAULT FALSE,
                                       PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE IF NOT EXISTS films_likes (
                                           user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                           film_id INTEGER NOT NULL REFERENCES films(film_id) ON DELETE CASCADE,
                                           PRIMARY KEY (user_id, film_id)
);